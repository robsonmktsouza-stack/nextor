    public static function for(string $field): ?string
    {
        if (strlen($field) > 500 || !preg_match('/^[a-zA-Z0-9_.*-]+$/D', $field)) {
            return 'campo informado';
        }
        $normalized = preg_replace('/(?<=\.)\d+(?=\.|$)/', '*', $field);
        if (self::$languageAliases === null) {
            $messages = require dirname(__DIR__, 2).'/lang/pt_BR/validation.php';
            self::$languageAliases = $messages['attributes'] ?? [];
        }
        if (isset(self::$languageAliases[$normalized])) return self::$languageAliases[$normalized];
        if (isset(self::LABELS[$normalized])) return self::LABELS[$normalized];
        $parts = explode('.', $normalized);
        $leaf = end($parts);
        if ($leaf === '*') $leaf = count($parts) > 1 ? $parts[count($parts)-2] : '';
        $label = self::$languageAliases[$leaf] ?? self::LABELS[$leaf] ?? FiscalPresentation::label($leaf);
        if ($label === null) return 'campo informado';
        if (str_starts_with($normalized, 'delivery_addresses.')) return $label.' do endereço de entrega';
        if (str_contains($normalized, '.state_variations.')) return $label.' da variação por UF';
        if (str_contains($normalized, '.municipal_variations.')) return $label.' da variação por município';
        if (str_starts_with($normalized, 'items.')) return $label.' do item';
        if (str_starts_with($normalized, 'payments.')) return $label.' do pagamento';
        return $label;
    }
